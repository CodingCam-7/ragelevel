const FONT_W = 5;
const FONT_H = 7;
const FONT_GAP = 1;            // blank columns between glyphs

/** Unknown characters draw as a hollow box so typos are obvious. */
const GLYPH_MISSING =
  '11111' + '10001' + '10001' + '10001' + '10001' + '10001' + '11111';

const Font = {
  /** Rendered width of a string at the given pixel scale. */
  width(str, scale) {
    if (!str.length) return 0;
    return (str.length * (FONT_W + FONT_GAP) - FONT_GAP) * scale;
  },

  height(scale) { return FONT_H * scale; },

  /**
   * @param x  left edge, or the centre / right edge depending on align
   * @param y  vertical centre of the text block
   */
  draw(ctx, str, x, y, color, scale, align) {
    scale = scale || 1;
    str = String(str).toUpperCase();

    const total = this.width(str, scale);
    let px = Math.round(align === 'center' ? x - total / 2
                      : align === 'right' ? x - total
                      : x);
    const py = Math.round(y - (FONT_H * scale) / 2);

    ctx.fillStyle = color;
    for (let i = 0; i < str.length; i++) {
      const g = GLYPHS[str[i]] || GLYPH_MISSING;
      for (let row = 0; row < FONT_H; row++) {
        for (let colIdx = 0; colIdx < FONT_W; colIdx++) {
          if (g[row * FONT_W + colIdx] === '1') {
            ctx.fillRect(px + colIdx * scale, py + row * scale, scale, scale);
          }
        }
      }
      px += (FONT_W + FONT_GAP) * scale;
    }
  }
};

/* Every glyph must be exactly 35 bits or it will render as garbage. */
for (const ch in GLYPHS) {
  if (GLYPHS[ch].length !== FONT_W * FONT_H) {
    console.error(`Glyph "${ch}" is ${GLYPHS[ch].length} bits, expected ${FONT_W * FONT_H}`);
  }
}
